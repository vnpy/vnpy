"""
Local paper-trading gateway.

It implements the same BaseGateway contract as a real broker gateway:
    * connect / close / subscribe / send_order / cancel_order
    * query_account / query_position
    * on_tick / on_order / on_trade / on_position / on_account / on_contract

Historical bars are replayed as ticks. Limit orders are matched against the
next tick, positions and cash are updated locally, and all updates are pushed
into the EventEngine exactly like a real gateway would do.

Replacing this class with vnpy_ctp / vnpy_xtp / vnpy_tora ... does not require
any change to the strategy code.
"""

from __future__ import annotations

import threading
from collections import defaultdict
from datetime import datetime
from pathlib import Path
from time import sleep

import pandas as pd

from vnpy.event import EventEngine
from vnpy.trader.constant import Direction, Exchange, Interval, Product, Status
from vnpy.trader.gateway import BaseGateway
from vnpy.trader.object import (
    AccountData,
    BarData,
    CancelRequest,
    ContractData,
    OrderData,
    OrderRequest,
    PositionData,
    SubscribeRequest,
    TickData,
    TradeData,
)


class SimGateway(BaseGateway):
    """Paper-trading gateway driven by a historical bar CSV file."""

    default_name: str = "SIM"

    # data_file : CSV generated by run.py
    # speed     : sleep seconds between two trading days
    default_setting: dict[str, str | int | float | bool] = {
        "data_file": "",
        "speed": 0.002,
        "capital": 1_000_000,
        "buy_rate": 0.0005,
        "sell_rate": 0.0015,
    }

    exchanges: list[Exchange] = [Exchange.SSE, Exchange.SZSE]

    def __init__(self, event_engine: EventEngine, gateway_name: str = "SIM") -> None:
        """Constructor"""
        super().__init__(event_engine, gateway_name)

        self._active: bool = False
        self._thread: threading.Thread | None = None
        self._finished: threading.Event = threading.Event()
        self._lock: threading.RLock = threading.RLock()

        # Market data
        self.bars: dict[str, dict[datetime, BarData]] = {}
        self.dates: list[datetime] = []
        self.subscribed: set[str] = set()
        self.contracts: dict[str, ContractData] = {}
        self.pre_closes: dict[str, float] = {}
        self.last_prices: dict[str, float] = {}
        self.current_datetime: datetime | None = None

        # Account and positions
        self.capital: float = 1_000_000.0
        self.cash: float = 0.0
        self.frozen_cash: float = 0.0
        self.pos: dict[str, float] = defaultdict(float)
        self.frozen_pos: dict[str, float] = defaultdict(float)
        self.avg_price: dict[str, float] = defaultdict(float)

        # Active orders and their frozen funds/positions
        self.active_orders: dict[str, OrderData] = {}
        self.order_frozen_cash: dict[str, float] = {}
        self.order_frozen_pos: dict[str, float] = {}

        # Statistics
        self.order_count: int = 0
        self.trade_count: int = 0
        self.total_commission: float = 0.0
        self.equity_curve: list[tuple[datetime, float]] = []

        # Fees
        self.buy_rate: float = 0.0005
        self.sell_rate: float = 0.0015
        self.min_commission: float = 5.0
        self.speed: float = 0.002

    # ------------------------------------------------------------------
    # BaseGateway interface
    # ------------------------------------------------------------------
    def connect(self, setting: dict) -> None:
        """Load bars, emit contracts/account, and start the replay thread."""
        data_file: Path = Path(str(setting.get("data_file", ""))).expanduser()
        if not data_file.is_absolute():
            data_file = data_file.resolve()

        if not data_file.exists():
            self.write_log(f"行情文件不存在：{data_file}")
            self._finished.set()
            return

        self.speed = float(setting.get("speed", 0.002))
        self.capital = float(setting.get("capital", 1_000_000))
        self.buy_rate = float(setting.get("buy_rate", 0.0005))
        self.sell_rate = float(setting.get("sell_rate", 0.0015))
        self.cash = self.capital

        # Keep leading zeros in stock codes such as 000001
        df: pd.DataFrame = pd.read_csv(
            data_file,
            parse_dates=["datetime"],
            dtype={"symbol": str},
        )

        required: set[str] = {
            "datetime", "symbol", "exchange", "interval",
            "open", "high", "low", "close", "volume", "turnover",
        }
        missing: set[str] = required.difference(df.columns)
        if missing:
            self.write_log(f"行情文件缺少字段：{sorted(missing)}")
            self._finished.set()
            return

        date_set: set[datetime] = set()

        row: object
        for row in df.itertuples(index=False):
            dt: datetime = row.datetime.to_pydatetime()
            bar: BarData = BarData(
                symbol=str(row.symbol),
                exchange=Exchange(row.exchange),
                datetime=dt,
                interval=Interval(row.interval),
                open_price=float(row.open),
                high_price=float(row.high),
                low_price=float(row.low),
                close_price=float(row.close),
                volume=float(row.volume),
                turnover=float(row.turnover),
                open_interest=0,
                gateway_name=self.gateway_name,
            )
            self.bars.setdefault(bar.vt_symbol, {})[dt] = bar
            date_set.add(dt)

        self.dates = sorted(date_set)

        # Emit contracts to OMS / UI
        vt_symbol: str
        bar_map: dict[datetime, BarData]
        for vt_symbol, bar_map in self.bars.items():
            first_bar: BarData = next(iter(bar_map.values()))
            contract: ContractData = ContractData(
                symbol=first_bar.symbol,
                exchange=first_bar.exchange,
                name=first_bar.symbol,
                product=Product.EQUITY,
                size=1,
                pricetick=0.01,
                min_volume=100,
                gateway_name=self.gateway_name,
            )
            self.contracts[vt_symbol] = contract
            self.on_contract(contract)

        self.write_log(
            f"模拟网关连接成功：{len(self.bars)} 个合约，"
            f"{len(self.dates)} 个交易日，初始资金 {self.capital:,.2f}"
        )
        self._push_account()

        self._active = True
        self._thread = threading.Thread(target=self._run_feed, daemon=True)
        self._thread.start()

    def close(self) -> None:
        """Stop the replay thread."""
        self._active = False

        if self._thread and self._thread.is_alive():
            self._thread.join(timeout=2)

    def subscribe(self, req: SubscribeRequest) -> None:
        """Subscribe one symbol."""
        with self._lock:
            self.subscribed.add(req.vt_symbol)

    def send_order(self, req: OrderRequest) -> str:
        """Validate, freeze funds/positions, and put the order into the active book."""
        with self._lock:
            self.order_count += 1
            order: OrderData = req.create_order_data(
                str(self.order_count),
                self.gateway_name
            )
            order.datetime = self.current_datetime
            self.on_order(order)

            contract: ContractData | None = self.contracts.get(req.vt_symbol)
            if contract is None:
                self._reject(order, "找不到合约")
                return order.vt_orderid

            if req.direction not in {Direction.LONG, Direction.SHORT}:
                self._reject(order, "仅支持多/空方向")
                return order.vt_orderid

            if req.volume <= 0:
                self._reject(order, "委托数量必须大于 0")
                return order.vt_orderid

            if req.volume % contract.min_volume != 0:
                self._reject(order, f"委托数量必须是 {contract.min_volume} 的整数倍")
                return order.vt_orderid

            price: float = req.price
            if price <= 0:
                price = self.last_prices.get(req.vt_symbol, 0.0)

            if price <= 0:
                self._reject(order, "没有可用的委托价格")
                return order.vt_orderid

            order.price = price

            if req.direction == Direction.LONG:
                required: float = price * req.volume * contract.size
                required += max(required * self.buy_rate, self.min_commission)

                if self.cash - self.frozen_cash < required:
                    self._reject(order, "可用资金不足")
                    return order.vt_orderid

                self.frozen_cash += required
                self.order_frozen_cash[order.vt_orderid] = required
            else:
                available: float = self.pos[req.vt_symbol] - self.frozen_pos[req.vt_symbol]
                if req.volume > available:
                    self._reject(order, "可平持仓不足")
                    return order.vt_orderid

                self.frozen_pos[req.vt_symbol] += req.volume
                self.order_frozen_pos[order.vt_orderid] = req.volume

            order.status = Status.NOTTRADED
            self.active_orders[order.vt_orderid] = order
            self.on_order(order)

            self.write_log(
                f"委托已接受：{order.vt_symbol} {req.direction.value} "
                f"{req.volume:g} @ {price:.2f}"
            )
            self._push_account()
            self._push_positions()
            return order.vt_orderid

    def cancel_order(self, req: CancelRequest) -> None:
        """Cancel an active order and release its frozen funds/positions."""
        with self._lock:
            vt_orderid: str = f"{self.gateway_name}.{req.orderid}"
            order: OrderData | None = self.active_orders.pop(vt_orderid, None)

            if order is None:
                return

            self._release_frozen(order)
            order.status = Status.CANCELLED
            self.on_order(order)

            self.write_log(f"委托已撤销：{order.vt_symbol} {order.vt_orderid}")
            self._push_account()
            self._push_positions()

    def query_account(self) -> None:
        """Push a fresh account snapshot."""
        with self._lock:
            self._push_account()

    def query_position(self) -> None:
        """Push fresh position snapshots."""
        with self._lock:
            self._push_positions()

    # ------------------------------------------------------------------
    # Replay loop
    # ------------------------------------------------------------------
    def _run_feed(self) -> None:
        """Replay bars as ticks, one trading day per loop."""
        dt: datetime
        for dt in self.dates:
            if not self._active:
                break

            self.current_datetime = dt

            with self._lock:
                subscribed: list[str] = list(self.subscribed)

            vt_symbol: str
            for vt_symbol in subscribed:
                bar: BarData | None = self.bars.get(vt_symbol, {}).get(dt)
                if bar is None:
                    continue

                with self._lock:
                    tick: TickData = self._create_tick(bar)

                # Orders sent on the previous tick are filled on this tick
                self._match_orders(tick)
                self.on_tick(tick)

                with self._lock:
                    self._push_account()
                    self._push_positions()

            sleep(self.speed)

        # End of replay: cancel outstanding orders so no funds stay frozen
        with self._lock:
            order: OrderData
            for order in list(self.active_orders.values()):
                self._release_frozen(order)
                order.status = Status.CANCELLED
                self.on_order(order)
                self.write_log(
                    f"收盘撤销未成交委托：{order.vt_symbol} {order.vt_orderid}"
                )

            self.active_orders.clear()
            self._push_account()
            self._push_positions()

        self._finished.set()
        self.write_log("模拟行情回放结束")

    def _create_tick(self, bar: BarData) -> TickData:
        """Convert a bar into a tick snapshot."""
        vt_symbol: str = bar.vt_symbol
        pre_close: float = self.pre_closes.get(vt_symbol, bar.open_price)

        tick: TickData = TickData(
            symbol=bar.symbol,
            exchange=bar.exchange,
            datetime=bar.datetime,
            name=bar.symbol,
            volume=bar.volume,
            turnover=bar.turnover,
            open_interest=0,
            last_price=bar.close_price,
            last_volume=bar.volume,
            limit_up=round(bar.close_price * 1.1, 2),
            limit_down=round(bar.close_price * 0.9, 2),
            open_price=bar.open_price,
            high_price=bar.high_price,
            low_price=bar.low_price,
            pre_close=pre_close,
            bid_price_1=round(bar.close_price - 0.01, 2),
            bid_volume_1=100,
            ask_price_1=round(bar.close_price + 0.01, 2),
            ask_volume_1=100,
            localtime=datetime.now(),
            gateway_name=self.gateway_name,
        )

        self.pre_closes[vt_symbol] = bar.close_price
        self.last_prices[vt_symbol] = bar.close_price
        return tick

    def _match_orders(self, tick: TickData) -> None:
        """Fill active limit orders that cross the new tick."""
        with self._lock:
            vt_orderid: str
            for vt_orderid in list(self.active_orders.keys()):
                order: OrderData = self.active_orders[vt_orderid]

                if order.vt_symbol != tick.vt_symbol:
                    continue

                if order.direction == Direction.LONG and tick.last_price <= order.price:
                    self._fill_order(order, min(order.price, tick.last_price), tick)
                elif order.direction == Direction.SHORT and tick.last_price >= order.price:
                    self._fill_order(order, max(order.price, tick.last_price), tick)

    def _fill_order(self, order: OrderData, fill_price: float, tick: TickData) -> None:
        """Fill one order completely and push order/trade events."""
        contract: ContractData = self.contracts[order.vt_symbol]
        turnover: float = fill_price * order.volume * contract.size
        vt_symbol: str = order.vt_symbol

        if order.direction == Direction.LONG:
            commission: float = max(turnover * self.buy_rate, self.min_commission)

            frozen: float = self.order_frozen_cash.pop(order.vt_orderid, 0.0)
            self.frozen_cash = max(0.0, self.frozen_cash - frozen)

            self.cash -= turnover + commission

            old_volume: float = self.pos[vt_symbol]
            new_volume: float = old_volume + order.volume

            self.avg_price[vt_symbol] = (
                self.avg_price[vt_symbol] * old_volume + fill_price * order.volume
            ) / new_volume
            self.pos[vt_symbol] = new_volume
        else:
            commission = max(turnover * self.sell_rate, self.min_commission)

            frozen_pos: float = self.order_frozen_pos.pop(order.vt_orderid, 0.0)
            self.frozen_pos[vt_symbol] = max(
                0.0, self.frozen_pos[vt_symbol] - frozen_pos
            )

            self.cash += turnover - commission
            self.pos[vt_symbol] -= order.volume

            if self.pos[vt_symbol] <= 0:
                self.pos[vt_symbol] = 0.0
                self.avg_price[vt_symbol] = 0.0

        self.total_commission += commission
        self.active_orders.pop(order.vt_orderid, None)

        order.traded = order.volume
        order.status = Status.ALLTRADED
        self.on_order(order)

        self.trade_count += 1
        trade: TradeData = TradeData(
            symbol=order.symbol,
            exchange=order.exchange,
            orderid=order.orderid,
            tradeid=str(self.trade_count),
            direction=order.direction,
            offset=order.offset,
            price=fill_price,
            volume=order.volume,
            datetime=tick.datetime,
            gateway_name=self.gateway_name,
        )
        self.on_trade(trade)

        self.write_log(
            f"成交：{trade.vt_symbol} {trade.direction.value} "
            f"{trade.volume:g} @ {fill_price:.2f}，手续费 {commission:.2f}"
        )

    def _reject(self, order: OrderData, reason: str) -> None:
        """Reject an order."""
        self._release_frozen(order)
        order.status = Status.REJECTED
        self.on_order(order)
        self.write_log(f"委托被拒绝：{order.vt_symbol}，原因：{reason}")

    def _release_frozen(self, order: OrderData) -> None:
        """Release frozen cash/position of an inactive order."""
        frozen_cash: float = self.order_frozen_cash.pop(order.vt_orderid, 0.0)
        if frozen_cash:
            self.frozen_cash = max(0.0, self.frozen_cash - frozen_cash)

        frozen_pos: float = self.order_frozen_pos.pop(order.vt_orderid, 0.0)
        if frozen_pos:
            self.frozen_pos[order.vt_symbol] = max(
                0.0, self.frozen_pos[order.vt_symbol] - frozen_pos
            )

    # ------------------------------------------------------------------
    # Snapshots
    # ------------------------------------------------------------------
    def _push_account(self) -> None:
        """Push account snapshot; balance = cash + market value."""
        holding_value: float = 0.0

        vt_symbol: str
        volume: float
        for vt_symbol, volume in self.pos.items():
            if not volume:
                continue

            contract: ContractData = self.contracts[vt_symbol]
            price: float = self.last_prices.get(vt_symbol, self.avg_price[vt_symbol])
            holding_value += volume * price * contract.size

        balance: float = self.cash + holding_value

        account: AccountData = AccountData(
            accountid="PAPER",
            balance=balance,
            frozen=self.frozen_cash,
            gateway_name=self.gateway_name,
        )
        self.on_account(account)

        dt: datetime = self.current_datetime or datetime.now()
        if not self.equity_curve or self.equity_curve[-1] != (dt, balance):
            self.equity_curve.append((dt, balance))

    def _push_positions(self) -> None:
        """Push position snapshots for all contracts, including flat positions."""
        vt_symbol: str
        contract: ContractData
        for vt_symbol, contract in self.contracts.items():
            volume: float = self.pos.get(vt_symbol, 0.0)
            frozen: float = self.frozen_pos.get(vt_symbol, 0.0)
            avg_price: float = self.avg_price.get(vt_symbol, 0.0)
            last_price: float = self.last_prices.get(vt_symbol, avg_price)
            pnl: float = (last_price - avg_price) * volume * contract.size

            position: PositionData = PositionData(
                symbol=contract.symbol,
                exchange=contract.exchange,
                direction=Direction.LONG,
                volume=volume,
                frozen=frozen,
                price=avg_price,
                pnl=pnl,
                yd_volume=volume,
                gateway_name=self.gateway_name,
            )
            self.on_position(position)

    # ------------------------------------------------------------------
    # Helpers for the runner / report
    # ------------------------------------------------------------------
    def is_finished(self) -> bool:
        """Whether the replay has finished."""
        return self._finished.is_set()

    def get_equity_curve(self) -> list[tuple[datetime, float]]:
        """Return a copy of the equity curve."""
        with self._lock:
            return list(self.equity_curve)

    def get_last_prices(self) -> dict[str, float]:
        """Return a copy of the latest prices."""
        with self._lock:
            return dict(self.last_prices)

    def get_total_commission(self) -> float:
        """Return total commission paid."""
        with self._lock:
            return self.total_commission
